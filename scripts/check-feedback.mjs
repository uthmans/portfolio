import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox'] });
const url = process.env.PORTFOLIO_URL || 'http://127.0.0.1:4173/portfolio/';
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(new URL('survey/', url).href);
  const section = page.locator('#written-feedback');
  assert.equal(await page.locator('input[type=file]').count(), 1);
  assert.equal(await section.getByRole('button').count(), await section.locator('.feedback-controls').count() ? 2 : 1);
  const finding = section.locator('.feedback-finding').first();
  await finding.locator('summary').click();
  assert.equal(await finding.locator('li').count(), 5);
  assert.match(await finding.innerText(), /Suggested next step/);
  const downloading = page.waitForEvent('download');
  await section.getByRole('button', { name: 'Download analysis report' }).click();
  const file = await downloading;
  assert.match(await readFile(await file.path(), 'utf8'), /Hand-written example/);
  await page.getByLabel('Learning track').selectOption('Websites');
  assert.match(await section.innerText(), /4 of 4 selected responses/);
  assert.equal(await section.locator('.feedback-finding').first().locator('li').count(), 3);
  await page.getByLabel('Learning track').selectOption('All');
  const input = page.getByLabel('Choose CSV file', { exact: true });
  await page.getByLabel('Number of responses', { exact: true }).fill('15');
  await page.getByRole('button', { name: 'Generate fictional dataset', exact: true }).click();
  await section.getByText(/15 of 15 selected responses include a written comment/).waitFor();
  assert.equal(await section.locator('.feedback-finding').count(), 0);
  await section.locator('.feedback-originals summary').click();
  assert.equal(await section.locator('.feedback-originals li').count(), 15);
  if (await section.locator('.feedback-controls').count()) assert.equal(await section.getByRole('checkbox').isVisible(), true);
  await page.getByRole('button', { name: 'Reset to sample', exact: true }).click();
  await input.setInputFiles({ name: 'bad.csv', mimeType: 'text/csv', buffer: Buffer.from('id,feedback\nx,test\n') });
  await page.getByRole('alert').waitFor();
  assert.equal(await section.locator('.feedback-finding').count(), 3);
  await input.setInputFiles({ name: 'survey.csv', mimeType: 'text/csv', buffer: Buffer.from('id,track,format,satisfaction,confidence,feedback\r\nx,Websites,Online,5,4,"Good examples, more time please."\r\ny,Data,Online,2,3,"A written recap would help."') });
  await section.getByText('2 of 2 selected responses include a written comment.', { exact: false }).waitFor();
  assert.equal(await section.locator('.feedback-finding').count(), 0);
  await section.locator('.feedback-originals summary').click();
  assert.match(await section.innerText(), /Good examples, more time please/);
  await page.getByLabel('Learning track').selectOption('Data');
  assert.match(await section.innerText(), /1 of 1 selected responses/);
  assert.equal(await section.locator('.feedback-originals li').count(), 1);
  const exportEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: /Download filtered CSV/ }).click();
  const csv = await exportEvent;
  assert.match(await readFile(await csv.path(), 'utf8'), /confidence,feedback\r\ny,Data,Online,2,3,A written recap would help/);
  await input.setInputFiles({ name: 'ratings.csv', mimeType: 'text/csv', buffer: Buffer.from('id,track,format,satisfaction,confidence\na,Data,Online,5,4') });
  await section.getByText(/No written comments in this selection/).waitFor();
  for (const width of [375, 768, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Overflow at ${width}`);
  }
  await page.addScriptTag({ path: 'node_modules/axe-core/axe.min.js' });
  const axe = await page.evaluate(async () => window.axe.run('#written-feedback', { runOnly: ['wcag2a', 'wcag2aa', 'wcag21aa'] }));
  assert.deepEqual(axe.violations.map(v => `${v.id}: ${v.description}`), []);
  assert.deepEqual(errors, []);
  console.log('Unified feedback checks passed: single upload, theme dropdowns, shared filters, comments export, invalid import preservation, report download, legacy CSV and responsive accessibility.');
} finally { await browser.close(); }
